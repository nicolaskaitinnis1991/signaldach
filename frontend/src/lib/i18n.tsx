// ---------------------------------------------------------------------------
// Context
// ---------------------------------------------------------------------------

interface I18nContextValue {
  locale: Locale;
  setLocale: (l: Locale) => void;
  t: (key: string) => string;
}

const I18nContext = createContext<I18nContextValue>({
  locale: DEFAULT_LOCALE,
  setLocale: () => {},
  t: (key: string) => key,
});

// ---------------------------------------------------------------------------
// Provider
// ---------------------------------------------------------------------------

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(DEFAULT_LOCALE);
  const [mounted, setMounted] = useState(false);

  // Load from localStorage on mount — only AFTER hydration
  useEffect(() => {
    try {
      const stored = localStorage.getItem(LS_KEY) as Locale | null;
      if (stored && translations[stored]) {
        setLocaleState(stored);
      }
    } catch {
      // SSR or localStorage unavailable
    }
    setMounted(true);
  }, []);

  const setLocale = useCallback((l: Locale) => {
    setLocaleState(l);
    try {
      localStorage.setItem(LS_KEY, l);
    } catch {
      // ignore
    }
  }, []);

  // Use DEFAULT_LOCALE until mounted to prevent hydration mismatch
  const activeLocale = mounted ? locale : DEFAULT_LOCALE;

  // Keep <html lang> in sync with the active locale
  useEffect(() => {
    if (mounted) {
      document.documentElement.lang = activeLocale;
    }
  }, [activeLocale, mounted]);

  const t = useCallback(
    (key: string): string => {
      // key format: "section.key" e.g. "sidebar.executive"
      const [section, ...rest] = key.split(".");
      const subKey = rest.join(".");
      const val = translations[activeLocale]?.[section]?.[subKey];
      if (val !== undefined) return val;
      // Fallback to English
      const fallback = translations.en?.[section]?.[subKey];
      if (fallback !== undefined) return fallback;
      // Return key itself as last resort
      return key;
    },
    [activeLocale]
  );

  return (
    <I18nContext.Provider value={{ locale: activeLocale, setLocale, t }}>
      {children}
    </I18nContext.Provider>
  );
}

// ---------------------------------------------------------------------------
// Hook
// ---------------------------------------------------------------------------

export function useTranslation() {
  return useContext(I18nContext);
}
